-- 테스트 인재(btwk2026+us*)의 옛 직군 이름을 현재 직군 체계의 이름으로 바꾼다.
--
-- 9월 말 테스트 계정 100개를 만들 때 옛 직종 목록(헤어·네일·두피관리·타투·바디아트 …)의 이름이 그대로 들어가
-- 대분류·소분류·직군이 모두 같은 옛 이름이었다. 지금 직군 목록(lib/data/jobGroups.ts)에 없는 이름이라 인재검색
-- 직군 필터·추천·이력서 어디에도 정식으로 걸리지 않는다. 샘플 데이터라 대응하는 정식 직군으로 배정한다
-- (옛 목록에 대응이 없는 「타투·바디아트」는 임의로 특수분장사(SFX)). 한줄소개 맨 앞의 「<옛 이름> 분야에서」도 같이 바꾼다.
-- 실제 가입자는 건드리지 않는다(이메일이 btwk2026+us 로 시작하는 테스트 계정만).

BEGIN;

WITH map(옛, 대, 소) AS (VALUES
  ('메이크업·아티스트', '메이크업',     '메이크업 아티스트'),
  ('헤어',              '헤어·바버',    '헤어디자이너'),
  ('피부관리·에스테틱', '피부·바디',    '피부 관리사(일반·경락)'),
  ('네일',              '네일·속눈썹',  '네일 아티스트'),
  ('왁싱·제모',         '피부·바디',    '왁싱·제모 전문가'),
  ('샵매니저',          '샵 운영·상담', '샵매니저'),
  ('마사지·테라피',     '피부·바디',    '바디 테라피스트·체형 관리사'),
  ('뷰티강사·교육',     '미용강사',     '교육강사'),
  ('타투·바디아트',     '메이크업',     '특수분장사(SFX)'),
  ('반영구·속눈썹',     '네일·속눈썹',  '속눈썹·반영구 아티스트'),
  ('두피관리',          '두피·탈모',    '두피 관리사'))
UPDATE user_profiles up
   SET main_job_group = map.대,
       sub_job = map.소,
       skill_areas = ARRAY[map.소],
       intro = CASE WHEN up.intro LIKE map.옛 || ' 분야에서%' THEN replace(up.intro, map.옛 || ' 분야에서', map.소 || ' 분야에서') ELSE up.intro END
  FROM users u, map
 WHERE u.id = up.user_id AND u.email LIKE 'btwk2026+us%'
   AND (up.main_job_group = map.옛 OR up.sub_job = map.옛 OR map.옛 = ANY(up.skill_areas));

COMMIT;
