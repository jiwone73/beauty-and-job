-- 여태는 한 통씩 보내다 실패해도 로그만 찍고 넘어간 뒤 끝에 무조건
-- status='sent' 를 적었다. 구독자 전원에게 실패해도 화면에는 「발송 완료」로
-- 남고, 달라지는 것은 sent_count 가 0 이 되는 것뿐이었다.
--
-- 보낸 수만 적혀 있어 「(1)」이 전부인지 아홉 중 하나인지 알 수 없었다.
-- 대상 수를 함께 적어 둘을 견주게 한다.
