-- 무료를 「평생 5회」에서 「라이트 7일 체험」으로 바꾼다.
--
-- 공고 건수를 막는 것은 우리에게 손해다. 공고가 많아야 구직자가 오고, 구직자가
-- 있어야 유료가 팔린다. 무료와 유료를 가르는 것은 건수가 아니라 **날짜**다.
--
-- 그래서 무료는 「라이트를 이레 동안 그대로 써 보는 것」이다. 그 이레 동안에는
-- 공고를 몇 건이든 걸 수 있고 내려가지 않는다. 이레가 지나면 걸려 있던 공고가
-- 내려가고, 계속 걸어 두려면 산다 — 그때가 라이트가 팔리는 자리다.
ALTER TABLE companies ADD COLUMN IF NOT EXISTS trial_until date;

COMMENT ON COLUMN companies.trial_until IS
  '무료 체험이 끝나는 날(이 날까지). 첫 공고를 거는 순간 오늘+7 로 정해진다. NULL 이면 아직 시작 전.';

-- free_posts_used 는 이제 문을 지키지 않는다. 지우지는 않는다 — 여태 몇 건을
-- 올렸는지가 남아 있어 나중에 수치를 볼 때 쓴다.
COMMENT ON COLUMN companies.free_posts_used IS
  '여태 올린 공고 수(기록용). 2026-09-15 부터 한도로 쓰지 않는다.';
