function LegalBlock({ b }: { b: any }) {
  if (b.p !== undefined) return <p>{b.p}</p>;
  if (b.h !== undefined) return <h4 className="legal-subtitle">{b.h}</h4>;
  if (b.t !== undefined) return (
    <div className="legal-table-wrap">
      <table className="legal-table">
        <thead>
          <tr>{b.t.head.map((h: string, j: number) => <th key={j}>{h}</th>)}</tr>
        </thead>
        <tbody>
          {b.t.rows.map((r: string[], ri: number) => (
            <tr key={ri}>{r.map((c: string, ci: number) => <td key={ci}>{c}</td>)}</tr>
          ))}
        </tbody>
      </table>
    </div>
  );
  return null;
}

