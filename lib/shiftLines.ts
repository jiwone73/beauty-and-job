// 근무요일/시간 값을 화면에 어떻게 줄로 나눠 보여줄지 — 공고 폼 카드와 미리보기·상세가
// 각자 다시 짜면 둘이 어긋난다("폼은 시간 옆에 (협의), 미리보기는 밑에 협의가능"). 값을
// 저장하는 형식(문장 끝 "(협의)")은 그대로 두고, "화면에 보일 줄"만 이 함수 하나로 정해
// 폼·미리보기·상세가 셋 다 이 함수를 부른다.
export type 시간표시줄 = { 글: string; 협의: boolean };

export function 시간표시줄들(원문: string): 시간표시줄[] {
  if (!원문) return [];
  // 협의 여지는 문장 맨 끝에 "(협의)"로 붙어 저장된다(근무요일/시간 창의 「협의」 체크).
  const 협의됨 = /\(\+?협의\)\s*$/.test(원문);
  const 기준 = 원문.replace(/\s*\(\+?협의\)\s*$/, "");
  // "/"도 예전 원티드식 자유 입력에서 쓰던 구분자라 줄바꿈과 함께 받는다.
  return 기준.split(/\n|\//).map((s) => s.trim()).filter(Boolean).map((줄) => ({
    글: 줄,
    // 시간이 적힌 줄에만 붙인다("10시 ~ 20시") — 요일만 있는 줄("월, 화")엔 안 붙는다.
    협의: 협의됨 && /~/.test(줄),
  }));
}
