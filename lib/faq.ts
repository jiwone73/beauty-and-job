/** 그 묶음의 갈래 이름들 — 적힌 차례 그대로 */
export const 갈래들 = (m: 묶음) => [...new Set(FAQ[m].map((f) => f.갈래))];

/** 검색 — 질문과 답 아무 데나 걸리면 된다 */
export const FAQ찾기 = (m: 묶음, 말: string) => {
  const k = 말.trim().toLowerCase();
  if (!k) return FAQ[m];
  return FAQ[m].filter((f) => (f.q + f.a).toLowerCase().includes(k));
};
