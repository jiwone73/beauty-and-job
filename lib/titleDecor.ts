// 공고 제목에서 장식 기호 줄을 걷어낸다.
//
// 카페 공고 제목에는 눈에 띄려고 "★☆★☆★☆…" 를 길게 붙이거나 "♥♥♥ … ♥♥♥" 로
// 감싸는 경우가 있다. 목록에서는 제목을 밀어내고, 상세 카드에서는 띄어쓰기가 없어
// 한 낱말로 취급돼 카드를 뚫고 나간다.
//
// 두 개 이상 이어진 것만 지운다. 하나만 쓴 것은 "준오헤어 대치점 ★ with청소업체",
// "♥파트너♥" 처럼 구분자나 강조로 쓰인 것이라 지우면 뜻이 상한다.

const DECOR = "★☆♥♡◆◇■□▲▼△▽●○◎∎♠♣✚✦✧⭐🔥💜💙❤️❤🌸🌟✨❣❤︎";

/** 두 개 이상 이어진 장식 기호를 걷어낸다(사이에 공백이 끼어 있어도 한 덩어리로 본다). */
export function stripTitleDecor(title: string): string {
  const run = new RegExp(`(?:[${DECOR}][ \\t]*){2,}`, "g");
  const t = String(title || "");
  // 장식이 없으면 손대지 않는다. 공백 정리 같은 곁다리 변경으로 멀쩡한 제목까지
  // 바꾸면, 무엇을 고쳤는지 나중에 알아볼 수 없다.
  if (!run.test(t)) return t;
  run.lastIndex = 0;
  return t
    .replace(run, " ")
    // 걷어내고 남은 앞뒤 구분자·공백 정리
    .replace(/[ \t]{2,}/g, " ")
    .replace(/^[\s/·|,-]+/, "")
    .replace(/[\s/·|,-]+$/, "")
    .trim();
}
