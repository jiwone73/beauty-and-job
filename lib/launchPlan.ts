/** 오픈일. 화면에 날짜를 직접 적지 않고 여기서 가져다 쓴다.
 *  (상용화 일정 화면은 없앴다 — 계획은 lib/commercePlan.ts, docs/상용화계획.md)
 */
export const 오픈일 = "2026-10-12";
/** 화면에 적는 오픈일. 「2026년 10월 12일」·「10월 12일」 두 벌이면 날짜를
 *  옮길 때 한쪽이 반드시 남는다 — 여기서 만들어 쓴다. */
export const 오픈일글 = (해포함 = false) => {
  const [y, m, d] = 오픈일.split("-").map(Number);
  return `${해포함 ? `${y}년 ` : ""}${m}월 ${d}일`;
};
