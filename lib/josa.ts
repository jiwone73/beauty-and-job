/** 이름 뒤 조사를 받침에 맞춰 고른다.
 *
 *  「정용희이 읽었습니다」처럼 조사를 붙박아 두면 받침 없는 이름에서 모두
 *  틀린다. 뷰티 업계 이름에 받침 없는 경우가 흔하다(수미·나연·지우).
 *
 *  「님」을 붙이면 받침이 항상 있으므로 조사가 하나로 정해진다 — 그래서
 *  이름을 부를 때는 님을 붙이는 쪽이 글도 자연스럽고 규칙도 단순하다.
 */
function 받침있나(말: string): boolean {
  const 끝 = (말 || "").trim().slice(-1);
  if (!끝) return false;
  const 코드 = 끝.charCodeAt(0);
  if (코드 < 0xac00 || 코드 > 0xd7a3) return false;   // 한글이 아니면 모른다
  return (코드 - 0xac00) % 28 !== 0;
}

/** 「정용희」 → 「정용희님이」, 「오지민」 → 「오지민님이」 */
export function 님(이름: string | null | undefined, 조사: "이/가" | "은/는" | "을/를" = "이/가"): string {
  const 말 = (이름 || "").trim();
  if (!말) return "";
  // 님을 붙이면 받침이 생기므로 앞쪽 조사가 된다.
  return 말 + "님" + { "이/가": "이", "은/는": "은", "을/를": "을" }[조사];
}

/** 님 없이 이름만 쓸 때. 받침을 보고 고른다. */
export function 조사(말: string | null | undefined, 조사: "이/가" | "은/는" | "을/를" = "이/가"): string {
  const v = (말 || "").trim();
  if (!v) return "";
  const 있 = 받침있나(v);
  const 표 = { "이/가": ["가", "이"], "은/는": ["는", "은"], "을/를": ["를", "을"] };
  return v + 표[조사][있 ? 1 : 0];
}
