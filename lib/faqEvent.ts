/**
 * 이벤트 기간에만 보이는 FAQ.
 *
 * lib/faq.ts 의 본문은 유료화 기준이다 — 이벤트가 끝나도 고칠 곳이 없게. 이벤트 중에만
 * 달라지는 것(무료 체험·메인 줄서기)은 여기 따로 두고, /api/plans 의 trial 이 있을 때만
 * 「이벤트」 갈래로 맨 앞에 붙인다. 스위치를 끄면(설정에서 months 제거) 이 갈래째 사라진다.
 */
import { 플랜, 스타트 } from "@/lib/companyPlans";
import type { 질문 } from "@/lib/faq";

export type 체험정보 = { plan: string; months: number; to: string };

const 날 = (iso: string) => {
  const [, m, d] = iso.split("-").map(Number);
  return `${m}월 ${d}일`;
};

export function 이벤트질문(체험: 체험정보): 질문[] {
  const 등급 = 플랜[체험.plan as keyof typeof 플랜]?.name ?? 플랜.PREMIUM.name;
  return [
    { 갈래: "이벤트", q: "이벤트 무료 체험은 누가, 언제부터 받나요?",
      a: [
        `${날(체험.to)}까지 기업회원으로 가입하신 곳이 대상입니다`,
        `가입 승인이 되는 날부터 ${체험.months}개월 동안 ${등급} 상품의 모든 기능을 무료로 쓰실 수 있습니다`,
        "별도 신청은 없습니다 — 승인되는 순간 자동으로 적용됩니다",
        "승인 전에는 체험이 시작되지 않고, 승인 대기 기간은 체험 기간에서 빠지지 않습니다",
      ] },
    { 갈래: "이벤트", q: "체험 기간에는 무엇을 쓸 수 있나요?",
      a: [
        `${스타트.name}와 달리 공고를 건수 제한 없이 올리실 수 있습니다`,
        "인재 이름·연락처 열람, 제안 보내기, 채팅, 관심 표시한 인재 추천까지 모두 쓰실 수 있습니다",
        "공고는 비회원에게도 노출됩니다",
        "인재 연락처는 가입 승인을 받은 기업회원에게만 열립니다",
      ] },
    { 갈래: "이벤트", q: "체험이 끝나면 어떻게 되나요?",
      a: `${스타트.name}(무료 회원)로 돌아갑니다. 자동 결제는 없고, 요금이 청구되는 일도 없습니다. 체험 기간에 올려 두신 공고는 그날 노출이 끝나고, 이후 새로 올리시는 공고는 무료 회원 기준(한 번에 ${스타트.무료건수}건, 회원에게만 노출)이 됩니다. 계속 쓰시려면 ${플랜.LIGHT.name}부터 신청하시면 됩니다.` },
    { 갈래: "이벤트", q: "이벤트 중 메인 채용관 노출 순서는 어떻게 정해지나요?",
      a: [
        "이벤트 기간에는 공고를 먼저 올리신 순서대로 프리미엄관, 스탠다드관 자리가 채워집니다",
        "같은 관 안에서는 최근에 로그인하신 매장이 앞에 옵니다",
        "자주 공고를 올리고 접속하실수록 앞 순서와 높은 관에 유리합니다",
        "유료화 이후에는 구매하신 상품 순서로 노출이 바뀝니다",
      ] },
    { 갈래: "이벤트", q: "이벤트 중 검색 목록 순서는 달라지나요?",
      a: "아니요. 검색 목록은 평소와 같이 상품 등급 순서이고, 같은 등급 안에서는 최근 로그인 순입니다. 체험으로 받은 등급도 같은 기준으로 서열에 포함됩니다." },
  ];
}
