/**
 * 보관한 일수를 이 플랜을 살 때 며칠로 쓰는가.
 *
 * **보관한 상품과 같은 상품에만 쓴다.** 라이트에서 보관한 스무 날은 라이트로만
 * 돌아온다. 값 비율로 환산해 다른 상품에 얹어 주던 때가 있었는데, 그러면
 * 「라이트를 싸게 사서 프리미엄으로 바꿔 쓰는 길」이 열리고 무엇보다 사는
 * 쪽에서 며칠이 붙을지를 미리 셈할 수가 없다.
 */
export function 보관환산(보관플랜: PlanId, 보관일: number, 살플랜: PlanId): number {
  return 보관일 > 0 && 보관플랜 === 살플랜 ? 보관일 : 0;
}

