/**
 * 이 플랜이 주는 것. 없는 줄은 빼고 돌려준다.
 *
 * `새것` 은 **바로 아래 플랜보다 나아진 줄**이다. 값을 더 내는 이유가 어느
 * 줄인지 카드에서 바로 보이게 하려고 표시한다 — 아래 플랜과 같은 줄까지
 * 강조하면 넉 장이 다 보라색이 되어 아무것도 도드라지지 않는다.
 */
export const 혜택 = (칸: 0 | 1 | 2 | 3): { 글: string; 새것: boolean }[] =>
  혜택줄
    .map((r) => ({ 글: r[칸], 새것: 칸 > 0 && !!r[칸] && r[칸] !== r[칸 - 1] }))
    .filter((x): x is { 글: string; 새것: boolean } => !!x.글);

