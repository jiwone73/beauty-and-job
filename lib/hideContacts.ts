// 공고 본문에 적힌 매장 연락처를 구직자에게 가린다.
//
// 카페·인스타에서 옮겨 온 공고에는 "문자 주세요 010-…" 이 본문에 그대로 있다.
// 그대로 두면 구직자가 매장에 바로 연락해 버려 뷰티워크를 거칠 이유가 없어진다.
// 지원은 우리 지원 버튼으로 받아야 매장에도 이력이 남고 우리도 성과를 안다.
//
// 화면에서만 가리면 API 응답(JSON)을 열어 볼 때 번호가 다 보인다. 그래서 서버가
// 내려보내기 전에 지운다. 원문은 DB에 그대로 두므로 관리자는 등록 화면에서
// 대조할 수 있고, 매장에 연락할 일도 있다.

export const APPLY_ONLY = "뷰티워크 온라인 지원";

export function hideContacts(t: string): string {
  return String(t || "")
    // 전화번호: 010-1234-5678 / 01012345678 / 02-123-4567 등 (구분자는 - . 공백)
    .replace(/(0\d{1,2})[-.\s]?(\d{3,4})[-.\s]?(\d{4})/g, APPLY_ONLY)
    .replace(/[\w.+-]+@[\w-]+\.[\w.-]+/g, APPLY_ONLY)
    // 아이디는 ":" 뒤에도 오고 괄호 안에도 온다 — "카카오톡(YMW1238)" 처럼.
    .replace(/(카카오톡|카톡|카카오\s*채널|카톡\s*채널|플러스\s*친구|오픈\s*채팅|카톡\s*아이디)\s*(?:[:：]\s*|[(（]\s*)?[A-Za-z0-9._-]{3,}[)）]?/g, APPLY_ONLY)
    // 아이디 없이 창구 이름만 적는 경우 — "카카오톡 오픈채팅 메세지로 이력서 제출".
    // '오픈' 은 반드시 '채팅·카톡' 이 뒤따를 때만 본다(신규 오픈·오픈 예정을 건드리지 않게).
    // 뒤에 붙는 '메세지로' 까지 함께 걷되, 문장이 "지원로" 로 끝나지 않도록 어미를 살린다.
    // 아래 '카톡으로 주세요' 규칙보다 먼저 와야 "오픈카톡" 에서 '오픈' 만 남지 않는다.
    .replace(
      /[ \t]*['\u2018\u2019"]?[ \t]*(?:카카오톡[ \t]*)?(?:오픈[ \t]*채팅|오픈[ \t]*카톡|카카오톡[ \t]*채널|카카오[ \t]*채널|카톡[ \t]*채널|플러스[ \t]*친구)[ \t]*['\u2018\u2019"]?(?:[ \t]*(?:추가|검색)(?:하[고신]|해서)?)?(?:[ \t]*(?:메세지|메시지|톡|디엠|DM))?([ \t]*(?:으로|로))?/gi,
      (_m, 어미) => (어미 ? `${APPLY_ONLY}으로` : APPLY_ONLY)
    )
    // 매장 SNS. 들어가 보면 DM·프로필에 번호가 있어 전화번호를 가린 뜻이 없어진다.
    // 주소 뒤 경로는 있을 수도 없을 수도 있다. "pf.kakao.com/_abc" 도 "pf.kakao.com" 도
    // 결국 그 창구로 오라는 말이라 똑같이 가린다(예전엔 슬래시가 있어야만 걸렸다).
    .replace(/(https?:\/\/)?(www\.)?(instagram\.com|facebook\.com|band\.us|threads\.net|[\w-]+\.kakao\.com|kakao\.com|blog\.naver\.com|cafe\.naver\.com|youtube\.com|youtu\.be|twitter\.com|x\.com|t\.me|line\.me)(\/[^\s)\]]*)?/gi, APPLY_ONLY)
    // 주소 없이 "인스타 @nail_shop" 처럼 계정만 적는 경우
    .replace(/(인스타(?:그램)?|insta(?:gram)?|카톡|틱톡)\s*[:：]?\s*@?[A-Za-z0-9._]{3,}/gi, APPLY_ONLY)
    // 창구를 여러 개 늘어놓는 경우 — "전화나 문자, 카톡으로 연락주시면".
    // 하나씩 보는 규칙만으로는 가운데 하나만 바뀌고 나머지가 남아, 여전히
    // 매장으로 연락하라는 말이 된다. 이어진 목록은 통째로 바꾼다.
    // (연결어가 하나라도 있어야 걸리므로 낱말 하나만 있는 문장은 건드리지 않는다.)
    .replace(/(?:전화|문자|카톡|카카오톡|메일|이메일|DM|디엠|인스타(?:그램)?)(?:\s*[나이와,·\/]\s*(?:전화|문자|카톡|카카오톡|메일|이메일|DM|디엠|인스타(?:그램)?))+/gi, APPLY_ONLY)
    // 번호를 지웠어도 "문자로 보내주세요" 가 남으면 여전히 매장에 연락하려 든다.
    .replace(/지원\s*방법\s*[:：]\s*(?:문자|전화|휴대폰|핸드폰|폰|이메일|메일|카톡|카카오톡|DM|디엠|인스타(?:그램)?)\s*(?:으로|로)?/gi, `지원방법: ${APPLY_ONLY} 시`)
    .replace(/(?:문자|전화|휴대폰|핸드폰|폰번호|톡|카톡|카카오톡|카카오\s*채널|플러스\s*친구|DM|디엠|이메일|메일|인스타(?:그램)?)\s*(?:으로|로)?\s*(?:만)?\s*(?:주세요|남겨\s*주세요|보내\s*주세요|연락\s*주세요|문의\s*주세요|지원\s*(?:해\s*)?주세요)/gi, "뷰티워크로 지원해 주세요")
    .replace(/(?:문자|전화|휴대폰|핸드폰|카톡|카카오톡|DM|디엠|이메일|메일)\s*(?:으로|로)(?=\s|$)/gi, `${APPLY_ONLY}으로`)
    // 바꾸고 나면 "위 번호로 뷰티워크로…" 처럼 앞뒤에 쓸모없는 말이 남는다. 문장이 읽히도록 걷어낸다.
    .replace(/(?:위|아래)?\s*(?:번호|연락처|주소)\s*(?:으로|로)\s*(?=뷰티워크)/g, "")
    .replace(/(?:인스타(?:그램)?|카톡|카카오톡|문자|전화|휴대폰|핸드폰|이메일|메일|DM|디엠)\s+(?=뷰티워크)/gi, "")
    .replace(new RegExp(`${APPLY_ONLY}\\s*(?:으로|로)?\\s*(?:보내\\s*주세요|남겨\\s*주세요|주세요)`, "g"), APPLY_ONLY)
    // "휴대폰 번호 남겨주세요" 처럼 번호를 달라는 말. 번호 자체는 위에서 지웠어도
    // 이 말이 남으면 구직자가 매장에 번호를 넘기려 든다.
    .replace(/(?:휴대폰|핸드폰|전화)\s*번호\s*(?:를|은|는)?\s*(?:남겨|알려|보내|주시|기재|적어)[^\n.!?]{0,12}/g, APPLY_ONLY)
    // "'카카오채널' 또는 문자로 이력서 제출" 처럼 창구를 나열하고 이력서를 달라는 문장
    .replace(/['\u2018\u2019"]?\s*(?:카카오\s*채널|카톡\s*채널|플러스\s*친구)\s*['\u2018\u2019"]?\s*(?:또는|이나|,)?\s*(?:문자|전화|메일|이메일)?\s*(?:로|으로)?\s*(?:이력서\s*)?(?:제출|접수|보내|주세요|지원)[^\n.!?]{0,10}/g, APPLY_ONLY)
    .replace(/이력서\s*(?:는|를)?\s*(?:카카오\s*채널|카톡|문자|메일|이메일)[^\n.!?]{0,14}(?:제출|접수|보내|주세요)/g, APPLY_ONLY)
    // 카카오채널·플러스친구는 공고에서 오직 연락 창구로만 쓰인다. 다른 뜻이 없으니
    // 낱말이 남아 있으면 그대로 바꾼다("카카오채널 또는 …으로 제출" 처럼 반쪽만 바뀌는 것 방지).
    // 다른 사이트·카페를 가리키는 말. "헤어인잡 보고 연락드렸습니다" 처럼
    // 어디서 봤는지 말하게 하는 문구가 공고에 그대로 실려 온다. 우리 공고에
    // 남의 사이트 이름이 실릴 이유가 없고, 구직자를 그리로 보내는 셈이 된다.
    .replace(/[^\n.!?]*(?:헤어인잡|알바몬|잡코리아|사람인|뷰티잡|셀렉미|워크넷|알바천국|당근|맨사|뷰앤잡|거사모|네이버\s*카페)[^\n.!?]*(?:보고|통해|에서\s*봤|공고\s*보)[^\n.!?]*[.!?~]?/g, "")
    .replace(/(?:헤어인잡|알바몬|잡코리아|사람인|뷰티잡|셀렉미|워크넷|알바천국|맨사|뷰앤잡|거사모)(?:에서|에|의|을|를|은|는)?/g, "")
    // 매장에 직접 찾아오라는 안내. 지원은 뷰티워크를 거쳐야 한다.
    // ('재방문 고객', '방문 고객'처럼 손님 얘기는 건드리지 않도록 지원과 붙은 것만 본다.)
    .replace(/(?:이력서\s*(?:지참|들고)\s*)?(?:직접\s*)?방문\s*(?:지원|접수|상담|면접|해\s*주세요|하세요|환영)/g, APPLY_ONLY)
    .replace(/직접\s*방문(?=\s|$|[.,])/g, APPLY_ONLY)
    // 아이디가 붙은 창구를 먼저 지우고 나면 "DM,뷰티워크 온라인 지원,문자 등" 처럼
    // 양옆에 다른 창구 이름만 남는다. 그대로 두면 여전히 DM·문자로 오라는 말이다.
    .replace(new RegExp(`(?:전화|문자|카톡|카카오톡|메일|이메일|DM|디엠|인스타(?:그램)?)\\s*[,·/]\\s*(?=${APPLY_ONLY})`, "gi"), "")
    .replace(new RegExp(`(?<=${APPLY_ONLY})\\s*[,·/]\\s*(?:전화|문자|카톡|카카오톡|메일|이메일|DM|디엠|인스타(?:그램)?)`, "gi"), "")
    // 같은 안내가 잇달아 나오면 한 번만 남긴다.
    .replace(new RegExp(`(${APPLY_ONLY})(?:[\\s,·/]*(?:또는|이나|및|,)?[\\s]*\\1)+`, "g"), "$1")
    .replace(/(뷰티워크로 지원해 주세요)(?:[\s,·/]*(?:또는|이나|및|,)?[\s]*\1)+/g, "$1")
    .replace(new RegExp(`${APPLY_ONLY}[\\s,·/]*(?:또는|이나|및)?[\\s]*(?=뷰티워크로 지원해 주세요)`, "g"), "")
    .replace(/[ \t]{2,}/g, " ")
    // 문구를 걷어내고 남은 빈 줄·앞머리 기호를 정리한다.
    .replace(/^[ \t]*[·\-*※]\s*$/gm, "")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

/** 배열·문자열 어느 쪽이 와도 같은 규칙으로 가린다. */
export function hideContactsIn<T extends string | string[] | null | undefined>(v: T): T {
  if (Array.isArray(v)) return v.map((x) => hideContacts(String(x))) as T;
  if (typeof v === "string") return hideContacts(v) as T;
  return v;
}
