/** 등록 이슈가 손을 떠났는가.
 *
 *  답글 머리에 붙이는 표시로 가른다. 여태 「[해결]」 하나만 보고 있어,
 *  [수정]·[검토]·[확인] 로 답한 43 건이 밀린 것으로 잡혔다 — 실제로 손댈
 *  것은 답글이 아예 없는 두 건뿐인데 머리줄에 45 가 떠 있었다.
 *
 *    [해결] 고쳤다            [수정] 파서를 고쳤다
 *    [검토] 어찌할지 정했다    [확인] 보았고 고치지 않기로 했다
 *
 *  화면과 머리줄이 같은 규칙을 봐야 숫자가 따로 놀지 않는다.
 */
export const 처리표시 = /\[(해결|수정|검토|확인)\]/;

export function 처리됐나(이슈: { replies?: { text?: string }[] } | null | undefined) {
  return (이슈?.replies || []).some((r) => 처리표시.test(r.text || ""));
}
